using System.Text.Json;

namespace Solus.Telemetry.Contracts;

/// <summary>Bounded correlation labels; none establishes authentication or storage authority.</summary>
public sealed class TelemetryExecution
{
    /// <summary>Copies bounded optional labels; the workflow attempt is positive when supplied.</summary>
    public TelemetryExecution(string? repository = null, string? workflowRunId = null, int? runAttempt = null,
        string? job = null, string? invocationKey = null)
    {
        Repository = repository is null ? null : Validation.Text(repository, 256);
        WorkflowRunId = workflowRunId is null ? null : Validation.Text(workflowRunId, 128);
        if (runAttempt is <= 0) throw new ArgumentException("A supplied workflow attempt must be positive.");
        RunAttempt = runAttempt; Job = job is null ? null : Validation.Text(job, 256);
        InvocationKey = invocationKey is null ? null : Validation.Text(invocationKey, 256);
    }
    /// <summary>Gets optional repository label.</summary>
    public string? Repository { get; }
    /// <summary>Gets optional workflow run label, represented as a string.</summary>
    public string? WorkflowRunId { get; }
    /// <summary>Gets optional positive workflow attempt.</summary>
    public int? RunAttempt { get; }
    /// <summary>Gets optional job label.</summary>
    public string? Job { get; }
    /// <summary>Gets optional caller correlation key for matrix or repeated calls.</summary>
    public string? InvocationKey { get; }
}

/// <summary>Terminal product classification, independent of telemetry delivery.</summary>
public sealed class TelemetryOutcome
{
    /// <summary>Validates classification and an optional bounded diagnostic identifier, never an exception body.</summary>
    public TelemetryOutcome(TelemetryOutcomeKind kind, string? code = null)
    {
        Kind = Validation.Defined(kind);
        if (code is not null && (Validation.Text(code, 64).Any(c => !char.IsAsciiLetterOrDigit(c) && c is not '_' and not '-' and not '.')))
            throw new ArgumentException("Outcome code must be a safe identifier.");
        Code = code;
    }
    /// <summary>Gets product classification.</summary>
    public TelemetryOutcomeKind Kind { get; }
    /// <summary>Gets optional safe product diagnostic code.</summary>
    public string? Code { get; }
}

/// <summary>One terminal observation of one physical product invocation, with producer-assigned transport identity.</summary>
public sealed class TelemetryRecord
{
    /// <summary>Copies and validates the bounded public record; full-record byte admission happens before JSON is returned.</summary>
    /// <remarks>Reuse event identity across transport retries; a new invocation receives a new producer-created identity.</remarks>
    public TelemetryRecord(Guid eventId, string invocationId, DateTimeOffset occurredAt, string product, string productVersion,
        TelemetryExecution execution, TelemetryOutcome outcome, TelemetryUsage usage, JsonElement extensions)
    {
        EventId = Validation.Identity(eventId); InvocationId = Validation.Text(invocationId, 256);
        if (occurredAt.Offset != TimeSpan.Zero || occurredAt == default) throw new ArgumentException("A nondefault UTC timestamp is required.");
        OccurredAt = occurredAt; Product = Validation.Product(product); ProductVersion = Validation.Text(productVersion, 128);
        ArgumentNullException.ThrowIfNull(execution); ArgumentNullException.ThrowIfNull(outcome); ArgumentNullException.ThrowIfNull(usage);
        Execution = execution; Outcome = outcome; Usage = usage;
        Extensions = ExtensionValidation.Snapshot(extensions, product);
    }
    /// <summary>Gets the v1 wire discriminator, independent of package version.</summary>
    public int SchemaVersion => 1;
    /// <summary>Gets immutable producer event identity, never generated by serialization.</summary>
    public Guid EventId { get; }
    /// <summary>Gets the physical product invocation correlation label.</summary>
    public string InvocationId { get; }
    /// <summary>Gets UTC observation time.</summary>
    public DateTimeOffset OccurredAt { get; }
    /// <summary>Gets canonical product namespace.</summary>
    public string Product { get; }
    /// <summary>Gets product version label, not wire schema version.</summary>
    public string ProductVersion { get; }
    /// <summary>Gets bounded execution correlation labels.</summary>
    public TelemetryExecution Execution { get; }
    /// <summary>Gets terminal product outcome, not upload success.</summary>
    public TelemetryOutcome Outcome { get; }
    /// <summary>Gets current-run summaries without historical membership or implicit totals.</summary>
    public TelemetryUsage Usage { get; }
    /// <summary>Gets owned immutable product/caller JSON; producers own its vocabulary and content sanitization.</summary>
    public JsonElement Extensions { get; }

    /// <summary>Adds only noncolliding caller members; product and fixed fields cannot be overwritten.</summary>
    public TelemetryRecord WithCallerAttributes(JsonElement attributes) => new(EventId, InvocationId, OccurredAt, Product,
        ProductVersion, Execution, Outcome, Usage, ExtensionValidation.AddCaller(Extensions, attributes, Product));
}
